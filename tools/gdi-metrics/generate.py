#!/usr/bin/env python3
"""Write crates/rebellion-render/src/gdi_metrics.rs: GDI's advances and
kerning for the game fonts' sizes (theme::original_font_ppem).

Run with FreeType's v35 interpreter, whose advances equal Arial's hdmx at
every ppem hdmx lists (checked 2026-10-31):

    FREETYPE_PROPERTIES=truetype:interpreter-version=35 \
        python3 tools/gdi-metrics/generate.py ARIAL.TTF ARIALBD.TTF

ARIAL.TTF and ARIALBD.TTF are Windows' own fonts (here Windows 10's,
copied out of the A0 VM). They stay outside Git; only these metrics are
written.
"""
import struct
import sys
from pathlib import Path

from PIL import ImageFont

# (bold, ppem) for each game font size (ghidra/notes/gdi-font-sizes.md).
FACES = [(False, 7), (False, 9), (False, 11), (False, 13), (False, 16), (False, 21),
         (False, 25), (True, 10), (True, 11), (True, 13), (True, 15)]
CODES = range(32, 256)


def tables(data):
    count = struct.unpack(">H", data[4:6])[0]
    out = {}
    for i in range(count):
        tag, _, offset, length = struct.unpack(">4sIII", data[12 + 16 * i:28 + 16 * i])
        out[tag.decode("latin1")] = (offset, length)
    return out


def glyph_ids(data, tabs):
    offset, _ = tabs["cmap"]
    for i in range(struct.unpack(">H", data[offset + 2:offset + 4])[0]):
        platform, encoding, sub = struct.unpack(">HHI", data[offset + 4 + 8 * i:offset + 12 + 8 * i])
        if platform == 3 and encoding == 1:
            sub += offset
            break
    seg = struct.unpack(">H", data[sub + 6:sub + 8])[0] // 2
    ends = struct.unpack(f">{seg}H", data[sub + 14:sub + 14 + 2 * seg])
    starts = struct.unpack(f">{seg}H", data[sub + 16 + 2 * seg:sub + 16 + 4 * seg])
    deltas = struct.unpack(f">{seg}h", data[sub + 16 + 4 * seg:sub + 16 + 6 * seg])
    range_base = sub + 16 + 6 * seg
    ranges = struct.unpack(f">{seg}H", data[range_base:range_base + 2 * seg])

    def gid(ch):
        code = ord(ch)
        for i, end in enumerate(ends):
            if code <= end:
                if code < starts[i]:
                    return 0
                if ranges[i] == 0:
                    return (code + deltas[i]) & 0xFFFF
                at = range_base + 2 * i + ranges[i] + 2 * (code - starts[i])
                glyph = struct.unpack(">H", data[at:at + 2])[0]
                return (glyph + deltas[i]) & 0xFFFF if glyph else 0
        return 0
    return gid


def kern_pairs(data, tabs):
    offset, _ = tabs["kern"]
    count = struct.unpack(">H", data[offset + 2:offset + 4])[0]
    at = offset + 4
    pairs = {}
    for _ in range(count):
        _, length, coverage = struct.unpack(">HHH", data[at:at + 6])
        if coverage >> 8 == 0:
            n = struct.unpack(">H", data[at + 6:at + 8])[0]
            for i in range(n):
                left, right, value = struct.unpack(">HHh", data[at + 14 + 6 * i:at + 20 + 6 * i])
                pairs[(left, right)] = value
        at += length
    return pairs


def text(code):
    try:
        return bytes([code]).decode("cp1252")
    except UnicodeDecodeError:
        return None


def main():
    regular, bold = sys.argv[1], sys.argv[2]
    faces = {}
    for weight, path in ((False, regular), (True, bold)):
        data = Path(path).read_bytes()
        tabs = tables(data)
        faces[weight] = (path, glyph_ids(data, tabs), kern_pairs(data, tabs))
    out = [
        "//! GDI's advances and kerning for the game fonts' sizes, generated by",
        "//! `tools/gdi-metrics/generate.py` from Windows 10's arial.ttf and",
        "//! arialbd.ttf (hdmx / v35-hinted advances and the `kern` table; the",
        "//! fonts themselves are not kept). Indexed by cp1252 code - 32.",
        "",
        "/// (bold, ppem, advance of each cp1252 code 32..=255 in pixels).",
        "pub(crate) const ADVANCES: &[(bool, u8, [u8; 224])] = &[",
    ]
    for weight, ppem in FACES:
        path, gid, _ = faces[weight]
        font = ImageFont.truetype(path, ppem, layout_engine=ImageFont.Layout.BASIC)
        row = []
        for code in CODES:
            ch = text(code)
            row.append(round(font.getlength(ch)) if ch and gid(ch) else 0)
        out.append(f"    ({str(weight).lower()}, {ppem}, [{', '.join(map(str, row))}]),")
    out.append("];")
    out.append("")
    out.append("/// (bold, left cp1252 code, right cp1252 code, kerning in font units of")
    out.append("/// 2048 to the em), sorted.")
    out.append("pub(crate) const KERNING: &[(bool, u8, u8, i16)] = &[")
    for weight in (False, True):
        _, gid, pairs = faces[weight]
        ids = {code: gid(text(code)) for code in CODES if text(code)}
        rows = []
        for left, lg in ids.items():
            for right, rg in ids.items():
                value = pairs.get((lg, rg), 0) if lg and rg else 0
                if value:
                    rows.append((left, right, value))
        for left, right, value in sorted(rows):
            out.append(f"    ({str(weight).lower()}, {left}, {right}, {value}),")
    out.append("];")
    Path("crates/rebellion-render/src/gdi_metrics.rs").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
